/**
 * 再描画要求の世代を数えて、最後に要求されたものだけが結果を公開できる
 * ようにする（latest-wins、issue #218）。
 *
 * Interactive View はWebviewからメッセージを受け取るたびに非同期処理を開始
 * するが、一致／無視／マスクパターンの評価はワーカースレッドで行われ、
 * パターンによっては完了まで数秒かかる。世代を持たないと、古い重い条件の
 * 計算中に届いた新しい軽い条件を先に描画した後で、古い結果が到着して最新
 * 表示を上書きできてしまう——ログ調査で「条件に一致しているように見えて
 * 実際は古い結果」という誤認につながる。
 *
 * 古い計算のキャンセルまでは行わない。正しさはこの判定だけで確保でき、
 * キャンセルはフィルタAPIまで伝播させる必要があって変更範囲が広いため
 * （issue #218 の案3）。
 */
export class RefreshRevisionGate {
  private latest = 0;

  /** 新しい再描画要求を始め、その世代番号を返す。 */
  begin(): number {
    this.latest += 1;
    return this.latest;
  }

  /**
   * その世代がまだ最新か。`await` のたびに確認し、`false` なら結果を捨てる
   * （後から始まった要求が既に走っている、または完了しているため）。
   */
  isCurrent(revision: number): boolean {
    return revision === this.latest;
  }
}
