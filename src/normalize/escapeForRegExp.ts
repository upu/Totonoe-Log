/**
 * 正規表現のメタ文字を打ち消し、文字列をリテラルとして扱えるようにする。
 *
 * ユーザーが書いた文字列（マスク対象のキー名、セベリティのトークン）を
 * 選択肢として正規表現へ埋め込む箇所が複数あるため共通化している。
 * エスケープ漏れは「`a.b` が `axb` に当たる」程度で済まず、`(` 一つで
 * 正規表現全体が壊れて実行時例外になるため、必ずここを通す。
 */
export function escapeForRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
